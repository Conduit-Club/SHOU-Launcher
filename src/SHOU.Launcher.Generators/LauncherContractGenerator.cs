using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using SHOU.Build.Generation;

namespace SHOU.Launcher.Generators;

[Generator(LanguageNames.CSharp)]
public sealed class LauncherContractGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var inputs = context.CompilationProvider.Select(static (_, _) => ClientBuildInputs.Capture());
        context.RegisterSourceOutput(inputs, static (output, values) =>
        {
            var b = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace SHOU.Launcher.Core.Configuration;\npublic sealed partial class BuildConfiguration {\nprivate static readonly System.Collections.Generic.IReadOnlyDictionary<string,string> EmbeddedValues = new System.Collections.Generic.Dictionary<string,string> {\n");
            foreach (var pair in values) b.Append("[").Append(ClientBuildInputs.Literal(pair.Key)).Append("] = ").Append(ClientBuildInputs.Literal(pair.Value)).Append(",\n");
            b.Append("};\n}\n");
            output.AddSource("BuildConfiguration.g.cs", SourceText.From(b.ToString(), Encoding.UTF8));
        });
        var registries = context.AdditionalTextsProvider.Where(static f => f.Path.EndsWith("settings.schema", StringComparison.Ordinal) || f.Path.EndsWith("lifecycle.registry", StringComparison.Ordinal))
            .Select(static (f, ct) => (Path: f.Path, Text: f.GetText(ct)?.ToString() ?? ""));
        context.RegisterSourceOutput(registries, static (output, file) =>
        {
            var names = file.Text.Split('\n').Select(line => line.Trim()).Where(line => line.Length > 0 && !line.StartsWith("#", StringComparison.Ordinal)).ToArray();
            if (names.Length == 0 || names.Distinct(StringComparer.Ordinal).Count() != names.Length || names.Any(n => n.Any(ch => !char.IsLetterOrDigit(ch) && ch != '_' && ch != '.')))
            {
                output.ReportDiagnostic(Diagnostic.Create(new DiagnosticDescriptor("SHOU001", "Invalid registry", "Registry must contain unique, nonempty identifiers: {0}", "Build", DiagnosticSeverity.Error, true), Location.None, System.IO.Path.GetFileName(file.Path)));
                return;
            }
            var type = file.Path.EndsWith("settings.schema", StringComparison.Ordinal) ? "GeneratedSettingsSchema" : "GeneratedLifecycle";
            var source = "// <auto-generated/>\nnamespace SHOU.Launcher.Core.Configuration;\npublic static partial class " + type + " { public static System.Collections.Generic.IReadOnlyList<string> Entries { get; } = System.Array.AsReadOnly(new string[] {" + string.Join(",", names.Select(ClientBuildInputs.Literal)) + "}); }\n";
            output.AddSource(type + ".g.cs", SourceText.From(source, Encoding.UTF8));
        });
    }
}
